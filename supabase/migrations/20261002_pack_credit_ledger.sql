update public.generationusage
set status = case
        when completed_at is not null then 'completed'
        when completed_at is null then 'released'
    end,
    credit_cost = coalesce(credit_cost, 1),
    reserved_at = coalesce(reserved_at, generated_at),
    released_at = case when completed_at is null then coalesce(released_at, generated_at) else released_at end,
    usage_month = coalesce(usage_month, date_trunc('month', generated_at at time zone 'UTC')::date)
where status is null;

