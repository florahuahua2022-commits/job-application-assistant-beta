-- Pack credit storage only. Prices validate manual grants; no payment provider is connected.

create table if not exists public.packcreditaccount (
    user_id uuid primary key references auth.users(id) on delete cascade,
    balance integer not null default 0 check (balance >= 0),
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now()
);

create table if not exists public.packcreditledger (
    id bigint generated by default as identity primary key,
    user_id uuid not null references auth.users(id) on delete cascade,
    entry_type text not null check (entry_type in ('grant_free', 'grant_manual_topup', 'debit_generation', 'release')),
    credits_delta integer not null check (credits_delta <> 0),
    pack_id uuid,
    package_code text check (package_code is null or package_code in ('single', 'starter', 'job_search', 'custom')),
    amount_cents integer check (amount_cents is null or amount_cents >= 0),
    currency text not null default 'AUD' check (currency = 'AUD'),
    note text,
    idempotency_key text not null unique,
    created_by_user_id uuid references auth.users(id),
    created_at timestamptz not null default now(),
    check (
        (entry_type in ('grant_free', 'grant_manual_topup', 'release') and credits_delta > 0)
        or (entry_type = 'debit_generation' and credits_delta < 0)
    )
);

create index if not exists packcreditledger_user_created_idx
    on public.packcreditledger(user_id, created_at);
create unique index if not exists packcreditledger_user_pack_entry_idx
    on public.packcreditledger(user_id, pack_id, entry_type)
    where pack_id is not null and entry_type in ('debit_generation', 'release');

create table if not exists public.globalmonthlyusage (
    month_start date primary key,
    reserved_count integer not null default 0 check (reserved_count >= 0),
    completed_count integer not null default 0 check (completed_count >= 0),
    updated_at timestamptz not null default now()
);

-- Beta history is free: every existing user starts with two lifetime credits.
insert into public.packcreditaccount (user_id, balance)
select id, 2 from auth.users
on conflict (user_id) do nothing;

insert into public.packcreditledger (
    user_id, entry_type, credits_delta, idempotency_key, note
)
select id, 'grant_free', 2, 'grant-free:' || id::text, 'Initial lifetime credits'
from auth.users
on conflict (idempotency_key) do nothing;

